def render_content(doc, content):
    for item in content:
        if item is None:
            continue
        if isinstance(item, list):
            add_bullet_list(doc, item)
        else:
            add_paragraph(doc, item)


def main():
    doc = Document()
    set_document_margins(doc)

    add_title(doc, "Экзаменационные ответы по психологии")
    add_subtitle(doc, "55 вопросов — краткие академические ответы")

    for i, (question, content) in enumerate(QUESTIONS, start=1):
        add_question(doc, i, question)
        render_content(doc, content)

    output_path = "/workspace/Экзамен_психология_ответы.docx"
    doc.save(output_path)
    print(f"Создан файл: {output_path}")
    print(f"Вопросов: {len(QUESTIONS)}")


if __name__ == "__main__":
    main()
